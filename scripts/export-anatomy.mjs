import { createServer } from 'node:http';
import { readFile, writeFile, mkdir, mkdtemp, rm, rename, access } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { chromium } from 'playwright';
import sharp from 'sharp';

const root = process.cwd();
const require = createRequire(import.meta.url);
const component = path.resolve(root, process.env.ANATOMY_COMPONENT_DIR || 'src/app/shared/components/anatomy-viewer');
const output = path.resolve(root, 'public/anatomy-static');
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const modelSource = process.env.ANATOMY_MODEL || 'https://pub-45dc79586604478fb0dcbe5c2e4a3497.r2.dev/anatomy-treethenics-draco.glb';
const temporary = await mkdtemp(path.join(os.tmpdir(),'treethenics-anatomy-'));
let server, browser;
try {
  await access(path.join(component,'anatomy-muscle-map.ts'));
  console.log('Loading model...');
  let model;
  if (/^https?:\/\//.test(modelSource)) {
    const response = await fetch(modelSource, { signal: AbortSignal.timeout(120000) });
    if (!response.ok) throw new Error(`GLB HTTP ${response.status}`);
    model = Buffer.from(await response.arrayBuffer());
  } else model = await readFile(path.resolve(root, modelSource));
  const bundled = await build({
    entryPoints:[path.join(scriptDir,'anatomy/export-browser.mjs')], bundle:true, write:false, format:'esm',
    plugins:[{ name:'anatomy-map',setup(b){ b.onResolve({filter:/^__anatomy_map__$/},()=>({path:path.join(component,'anatomy-muscle-map.ts')})); }}],
  });
  const js = bundled.outputFiles[0].contents;
  const frontAngle = Number(process.env.ANATOMY_FRONT_ANGLE || 0);
  if (!Number.isFinite(frontAngle)) throw new Error('ANATOMY_FRONT_ANGLE must be radians');
  const version = createHash('sha256').update(model).update(js).update(String(frontAngle)).digest('hex').slice(0,12);
  const staging = path.join(temporary,'assets'); await mkdir(staging);
  const dracoDir = path.resolve(path.dirname(require.resolve('three')),'../examples/jsm/libs/draco/gltf');
  server = createServer(async (req,res)=>{
    try {
      const url = new URL(req.url,'http://localhost').pathname;
      if (url === '/') { res.setHeader('Content-Type','text/html'); res.end('<!doctype html><script type="module" src="/app.js"></script>'); }
      else if (url === '/app.js') { res.setHeader('Content-Type','text/javascript'); res.end(js); }
      else if (url === '/model.glb') { res.setHeader('Content-Type','model/gltf-binary'); res.end(model); }
      else if (/^\/draco\/(draco_wasm_wrapper\.js|draco_decoder\.wasm|draco_decoder\.js)$/.test(url)) {
        res.setHeader('Content-Type',url.endsWith('.wasm')?'application/wasm':'text/javascript');
        res.end(await readFile(path.join(dracoDir,path.basename(url))));
      } else { res.statusCode=404;res.end(); }
    } catch(e) { res.statusCode=500;res.end(String(e)); }
  });
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  browser = await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-vulkan']});
  const page = await browser.newPage();
  page.on('pageerror',e=>console.error('Browser:',e.message));
  let count=0, bytes=0;
  await page.exposeFunction('saveAnatomyImage',async(name,png)=>{
    if (!/^(front|back)-(base|r\d+-(primary|secondary))$/.test(name)) throw new Error('Invalid asset name');
    const buffer = Buffer.from(png,'base64');
    const stats = await sharp(buffer).stats();
    if (stats.channels[3]?.max === 0) return false;
    const webp = await sharp(buffer).webp({lossless:true,effort:6}).toBuffer();
    await writeFile(path.join(staging,name+'.webp'),webp);
    count++;bytes+=webp.length;
    console.log(`Exported ${name} (${Math.round(webp.length/1024)} KB)`);
    return true;
  });
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  await page.waitForFunction(()=>typeof window.exportAnatomy==='function');
  await page.evaluate(a=>window.frontAngle=a,frontAngle);
  const report = await page.evaluate(()=>window.exportAnatomy());
  await writeFile(path.join(staging,'report.json'),JSON.stringify({...report,version,count,bytes},null,2));
  const generated = `// Generated by scripts/export-anatomy.mjs. Do not edit.\nimport type { ExerciseMuscle } from '../../models/exercise-muscle.model';\n\nexport const ANATOMY_ASSETS: { version: string; width: number; height: number; layers: Record<'front' | 'back', { id: string; muscles: ExerciseMuscle[] }[]> } = ${JSON.stringify({version,width:report.width,height:report.height,layers:report.layers},null,2)};\n`;
  await mkdir(output,{recursive:true});
  const target = path.join(output,version);
  try { await access(target); } catch { await mkdir(target); }
  // Write assets before the manifest. Old version folders remain intact for safe deploys.
  const { readdir, copyFile } = await import('node:fs/promises');
  for (const file of await readdir(staging)) await copyFile(path.join(staging,file),path.join(target,file));
  const manifest = path.join(component,'anatomy-assets.generated.ts');
  await writeFile(manifest+'.tmp',generated);await rename(manifest+'.tmp',manifest);
  console.log(`Done: ${count} reusable images, ${(bytes/1024/1024).toFixed(2)} MB total. Version ${version}`);
  if (report.unmatchedMuscles.length) console.warn('No matching mesh (review report.json):',report.unmatchedMuscles.join(', '));
} finally {
  await browser?.close();
  if(server) await new Promise(resolve=>server.close(resolve));
  await rm(temporary,{recursive:true,force:true});
}
